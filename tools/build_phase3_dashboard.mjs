import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const output=path.join(root,'supabase/functions/pvp-verify-v3/dashboard_single_file.ts');
const result=await build({absWorkingDir:root,entryPoints:['supabase/functions/pvp-verify-v3/index.ts'],bundle:true,platform:'neutral',format:'esm',target:'es2022',write:false,metafile:true});
if(result.metafile.outputs[Object.keys(result.metafile.outputs)[0]].imports.length) throw Error('Dashboard bundle must have ZERO external/local imports');
const header=`// @ts-nocheck -- GENERATED JavaScript engine bundle, not hand-maintained TypeScript.
// Generated by: node tools/build_phase3_dashboard.mjs
// Paste THIS ENTIRE FILE into Dashboard index.ts. Function name: pvp-verify-v3.
// JWT verification: ON. Staging cuyqchmdcnsgzkwyclji only.
// No custom secrets/access token. Built-in SUPABASE_* credentials are read only at runtime.
// Do not paste credentials into this file. Source parity, engine and SQL tests cover this bundle.
// Regenerate after handler/engine changes; never edit this generated copy directly.
\n`;
const content=header+result.outputFiles[0].text;
if(process.argv.includes('--check')) {
 if(await readFile(output,'utf8')!==content) throw Error('stale Dashboard single file; run node tools/build_phase3_dashboard.mjs');
} else await writeFile(output,content);
console.log(`Dashboard standalone: ${Buffer.byteLength(content)} bytes, zero imports, ${Object.keys(result.metafile.inputs).length} inlined inputs`);
