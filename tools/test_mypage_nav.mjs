store.set('vrTcgStory.v1:tester',JSON.stringify({v:1,openingSeen:true,starter:null,owned:[{uid:'u1',id:'10325',level:50,boost:{}}],points:0,cleared:{'0':[1]},leader:'u1',decks:[{name:'',uids:['u1']}],statV:1}));
